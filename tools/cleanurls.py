"""PHP pages, tidy folders, clean URLs (last build step).

build.py and i18n.py write <page>.html into the root and /<lang>/. This moves every page to

    pages/<lang>/<page>.php        (lang: tr, en, de, ar, zh, ru)
    pages/<lang>/blog/<page>.php   (articles: og:type "article")

rewrites the links so no URL shows an extension (hakkimizda.html -> hakkimizda, index.html -> ./ or /en/) and writes
.htaccess. The public addresses do not change: /hakkimizda is served from pages/tr/hakkimizda.php, /en/seo-nedir from
pages/en/blog/seo-nedir.php; old /x.html and /x.php addresses 301 to the clean one, /pages/... itself is a 404.
Needs Apache with mod_rewrite and PHP (php -S / python -m http.server do not read .htaccess).
"""
import os, re, shutil

SITE = 'https://cyftech.com.tr'
LANGS = ['en', 'de', 'ar', 'zh', 'ru']
PAGES_DIR = 'pages'
# old service pages -> sections of web-cozumleri
MOVED = [('web-tasarim', 'web-cozumleri#web-tasarim'), ('web-gelistirme', 'web-cozumleri#web-gelistirme'),
         ('seo-hizmetleri', 'web-cozumleri#seo'), ('e-ticaret-siteleri', 'web-cozumleri#e-ticaret')]

_LANG_RE = '|'.join(LANGS)
# absolute page URLs on our own site (canonical, og:url, hreflang, structured data, sitemap)
ABS = re.compile(re.escape(SITE) + r'/((?:(?:' + _LANG_RE + r')/)?)([\w-]+)\.html\b')
# relative page URLs inside an attribute / string: href="hakkimizda.html#x", "../en/index.html", url=web-cozumleri.html
REL = re.compile(r'''(?<=["'=])((?:\.\./)?(?:(?:''' + _LANG_RE + r''')/)?)([\w-]+)\.html(?=[#"'?])''')

HTACCESS = r'''# Generated by tools/cleanurls.py — edit it there.
# Pages live in pages/<lang>/(blog/)<name>.php and are served at /<name> (Turkish) or /<lang>/<name>.
Options -MultiViews -Indexes
AddDefaultCharset UTF-8
RewriteEngine On

# build sources, dot-folders (.git) and the page files themselves are not public addresses
RewriteRule ^tools(/|$) - [F,L]
RewriteRule (^|/)\.(?!well-known/) - [F,L]
RewriteCond %{THE_REQUEST} \s/+pages[/\s?] [NC]
RewriteRule ^ - [R=404,L]

# old service pages -> sections of /web-cozumleri
__MOVED__
# old addresses -> clean ones (301): /index.html, /en/index.php -> /, /en/ ; /hakkimizda.html|.php -> /hakkimizda
RewriteCond %{THE_REQUEST} \s/+((?:[^\s?]*/)?)index\.(?:html|php)[\s?] [NC]
RewriteRule ^ /%1 [R=301,L,NE]
RewriteCond %{THE_REQUEST} \s/+([^\s?]+?)\.(?:html|php)[\s?] [NC]
RewriteRule ^ /%1 [R=301,L,NE]

# /en -> /en/ ; /hakkimizda/ -> /hakkimizda
RewriteRule ^(__LANGS__)$ /$1/ [R=301,L]
RewriteCond $1 !^(__LANGS__)$
RewriteRule ^(.+)/$ /$1 [R=301,L]

# clean address -> page file
RewriteRule ^$ pages/tr/index.php [L]
RewriteRule ^(__LANGS__)/$ pages/$1/index.php [L]
RewriteCond %{DOCUMENT_ROOT}/pages/$1/$2.php -f
RewriteRule ^(__LANGS__)/([\w-]+)$ pages/$1/$2.php [L]
RewriteCond %{DOCUMENT_ROOT}/pages/$1/blog/$2.php -f
RewriteRule ^(__LANGS__)/([\w-]+)$ pages/$1/blog/$2.php [L]
RewriteCond %{DOCUMENT_ROOT}/pages/tr/$1.php -f
RewriteRule ^([\w-]+)$ pages/tr/$1.php [L]
RewriteCond %{DOCUMENT_ROOT}/pages/tr/blog/$1.php -f
RewriteRule ^([\w-]+)$ pages/tr/blog/$1.php [L]
'''


def htaccess():
    moved = ''.join(f'RewriteRule ^{old}(?:\\.html|\\.php)?/?$ /{new} [R=301,NE,L]\n' for old, new in MOVED)
    return HTACCESS.replace('__MOVED__\n', moved).replace('__LANGS__', _LANG_RE)


def clean(text):
    def abs_url(m):
        return f'{SITE}/{m.group(1)}' + ('' if m.group(2) == 'index' else m.group(2))

    def rel_url(m):
        if m.group(2) != 'index':
            return m.group(1) + m.group(2)
        return m.group(1) or './'
    return REL.sub(rel_url, ABS.sub(abs_url, text))


def convert(root):
    out = os.path.join(root, PAGES_DIR)
    if os.path.isdir(out):
        shutil.rmtree(out)  # fully regenerated below
    n = 0
    for lang in ['tr'] + LANGS:
        src_dir = root if lang == 'tr' else os.path.join(root, lang)
        if not os.path.isdir(src_dir):
            continue
        for name in sorted(os.listdir(src_dir)):
            src = os.path.join(src_dir, name)
            if name.endswith('.php'):  # left over from an older layout
                os.remove(src)
                continue
            if not name.endswith('.html'):
                continue
            with open(src, encoding='utf-8') as f:
                html = f.read()
            if '<?' in html:
                raise SystemExit(f'cleanurls: {src} contains "<?", which PHP would try to run')
            sub = 'blog' if '<meta property="og:type" content="article">' in html else ''
            dst_dir = os.path.join(out, lang, sub)
            os.makedirs(dst_dir, exist_ok=True)
            with open(os.path.join(dst_dir, name[:-5] + '.php'), 'w', encoding='utf-8', newline='\n') as f:
                f.write(clean(html))
            os.remove(src)
            n += 1
        if lang != 'tr' and not os.listdir(src_dir):
            os.rmdir(src_dir)
    sm = os.path.join(root, 'sitemap.xml')
    if os.path.exists(sm):
        with open(sm, encoding='utf-8') as f:
            xml = f.read()
        with open(sm, 'w', encoding='utf-8', newline='\n') as f:
            f.write(clean(xml))
    with open(os.path.join(root, '.htaccess'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(htaccess())
    print(f'cleanurls: {n} pages -> {PAGES_DIR}/<lang>/(blog/)<name>.php, extensionless links, .htaccess')


def page_file(root, page, lang='tr'):
    """The file behind a page name written as <name>.html (before or after convert())."""
    name = page[:-5] + '.php'
    for p in (os.path.join(root, PAGES_DIR, lang, name), os.path.join(root, PAGES_DIR, lang, 'blog', name)):
        if os.path.exists(p):
            return p
    return os.path.join(root, page) if lang == 'tr' else os.path.join(root, lang, page)
